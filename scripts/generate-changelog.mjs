#!/usr/bin/env node
/**
 * git log를 KST 날짜별로 묶어 lib/changelog.generated.ts 를 씁니다.
 * 런타임에 .git 을 읽지 않습니다. predev / prebuild / prepare / pre-commit 에서 돌립니다.
 */
import { execFileSync } from "node:child_process";
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const overridesPath = join(root, "scripts/changelog-overrides.json");
const outPath = join(root, "lib/changelog.generated.ts");

/** @type {Record<string, { title?: string; body?: string }>} */
const overrides = JSON.parse(readFileSync(overridesPath, "utf8"));

function gitLog() {
  const raw = execFileSync(
    "git",
    [
      "-c",
      "log.showSignature=false",
      "log",
      "--no-merges",
      "--pretty=format:%H%x1f%ad%x1f%s%x1f%b%x1e",
      "--date=format:%Y-%m-%d",
    ],
    {
      cwd: root,
      env: { ...process.env, TZ: "Asia/Seoul" },
      encoding: "utf8",
    },
  );
  return raw
    .split("\x1e")
    .map((chunk) => chunk.trim())
    .filter(Boolean)
    .map((chunk) => {
      const [hash, date, subject, body = ""] = chunk.split("\x1f");
      return {
        hash: (hash || "").trim(),
        date: (date || "").trim(),
        subject: (subject || "").trim(),
        body: body.replace(/^\n+/, ""),
      };
    })
    .filter((row) => row.hash && row.date && row.subject);
}

function stripMeta(body) {
  return body
    .split(/\r?\n/)
    .filter((line) => !/^(Co-authored-by|Signed-off-by|Change-Id):/i.test(line))
    .join("\n")
    .trim();
}

function parseTrailers(body) {
  let title = "";
  /** @type {string | undefined} */
  let explicitBody;
  const rest = [];
  for (const line of stripMeta(body).split(/\r?\n/)) {
    const match = /^(Changelog(?:-Title)?|Changelog-Body):\s*(.*)$/i.exec(line);
    if (!match) {
      rest.push(line);
      continue;
    }
    if (/body/i.test(match[1])) explicitBody = match[2].trim();
    else title = match[2].trim();
  }
  return { title, explicitBody, rest: rest.join("\n").trim() };
}

function hasHangul(text) {
  return /[\uAC00-\uD7A3]/.test(text);
}

function entryFor(commit) {
  const trailers = parseTrailers(commit.body);
  const override = overrides[commit.subject];
  if (trailers.title || trailers.explicitBody !== undefined) {
    return {
      title: trailers.title || override?.title || commit.subject,
      body: trailers.explicitBody || trailers.rest || override?.body || "",
    };
  }
  if (override) {
    return {
      title: override.title || commit.subject,
      body: override.body || "",
    };
  }
  if (hasHangul(commit.subject)) {
    return { title: commit.subject, body: stripMeta(commit.body) };
  }
  return { title: commit.subject, body: "" };
}

function buildDays(commits) {
  /** @type {Map<string, { title: string; body: string }[]>} */
  const byDate = new Map();
  for (const commit of commits) {
    const entry = entryFor(commit);
    const list = byDate.get(commit.date) ?? [];
    const prev = list[list.length - 1];
    if (prev && prev.title === entry.title && prev.body === entry.body) continue;
    list.push(entry);
    byDate.set(commit.date, list);
  }
  return [...byDate.entries()]
    .sort(([a], [b]) => b.localeCompare(a))
    .map(([date, entries]) => ({ date, entries }));
}

const days = buildDays(gitLog());
const file = `// Generated by scripts/generate-changelog.mjs from git log. Do not edit.
export const CHANGELOG = ${JSON.stringify(days, null, 2)};
`;
writeFileSync(outPath, file);
try {
  execFileSync("git", ["config", "core.hooksPath", ".githooks"], { cwd: root, stdio: "ignore" });
} catch {
  // not a git checkout (or no permission)
}
const count = days.reduce((sum, day) => sum + day.entries.length, 0);
console.log(`changelog: ${days.length}일 · ${count}건 → lib/changelog.generated.ts`);
